import {loadEnvConfig} from '@next/env';
import {Pool} from 'pg';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {getPgPool,databaseError} from '../lib/postgres';
import {getPostgresState,mutatePostgres} from '../lib/postgres-store';
import {limaDate,type State} from '../lib/inventory';
import type {Actor} from '../lib/access';
import {inventoryForActor,readOperationHistory} from '../lib/operation-history-store';
import {seedSupplies} from '../lib/supplies-store';
import {getClosingDraft,saveClosingDraft,DraftConflictError} from '../lib/closing-drafts';

loadEnvConfig(process.cwd());
process.env.INVENTORY_STORAGE='postgres';
if(!['localhost','127.0.0.1','::1'].includes(process.env.PGHOST||'localhost'))throw new Error('Solo PostgreSQL local de prueba.');
async function main(){
  const pool=getPgPool();
  const schema=`lune_beta_${crypto.randomUUID().replaceAll('-','')}`;
  const globals=globalThis as typeof globalThis&{lunePgPool?:Pool};
  let isolated:Pool|undefined;
  let created=false;
  try{
    await pool.query(`CREATE SCHEMA "${schema}"`);created=true;
    isolated=new Pool({...pool.options,options:`-c timezone=America/Lima -c search_path=${schema}`,max:4});
    globals.lunePgPool=isolated;
    const sql=async(name:string)=>{await isolated!.query((await readFile(`database/${name}`,'utf8')).replaceAll('public.',`"${schema}".`));};
    for(const name of ['schema.sql','002_control.sql','005_insumos.sql','007_alertas_excel.sql'])await sql(name);
    const client=await isolated.connect();try{await seedSupplies(client);}finally{client.release();}
    await isolated.query(`CREATE TABLE perfiles_acceso(auth_id uuid PRIMARY KEY,nombre text,rol text,activo boolean,cambiar_password boolean,version_acceso integer DEFAULT 1);
      CREATE TABLE auditoria_acceso(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,auth_id uuid,accion text,detalle jsonb,creado_en timestamptz DEFAULT now());
      CREATE TABLE sesiones_revocadas(session_id uuid PRIMARY KEY,auth_id uuid);
      CREATE TABLE sesiones_aplicacion(session_id uuid PRIMARY KEY,auth_id uuid,version_acceso integer);
      CREATE TABLE limites_acceso(clave text PRIMARY KEY,intentos integer,vence_en timestamptz);
      INSERT INTO categorias(nombre_categoria) VALUES('Postres'),('Bollería');
      INSERT INTO ubicaciones(nombre_ubicacion,tipo) VALUES('Congelador','congelador'),('Mostrador','mostrador');
      INSERT INTO usuarios(nombre_usuario,password_hash,rol,activo) VALUES('Shalu','!','mostrador',true);
      INSERT INTO productos(id_categoria,nombre_producto,rendimiento,stock_minimo,activo) VALUES(1,'Pistacho prueba',1,1,true),(1,'Sacher prueba',1,1,true);`);
    const yesterday=new Date(Date.parse(`${limaDate()}T12:00:00Z`)-86400000).toISOString().slice(0,10);
    await isolated.query("INSERT INTO turnos(fecha,periodo,id_responsable,estado) VALUES($1,'tarde',1,'abierto')",[yesterday]);
    await isolated.query('INSERT INTO detalle_turno(id_turno,id_producto,entrada) SELECT 1,id_producto,0 FROM productos');
    for(const name of ['012_operacion_simple.sql','013_borradores.sql','015_catalogo_operacion.sql','016_insumos_salon.sql','017_cambio_mozo.sql'])await sql(name);
    const admin:Actor={id:crypto.randomUUID(),name:'Administración',role:'admin',mustChangePassword:false};
    const salon:Actor={id:crypto.randomUUID(),name:'Salón',role:'mozo',mustChangePassword:false};
    const cocina:Actor={id:crypto.randomUUID(),name:'Cocina',role:'cocina',mustChangePassword:false};
    for(const actor of [admin,salon,cocina])await isolated.query('INSERT INTO perfiles_acceso VALUES($1,$2,$3,true,false,1)',[actor.id,actor.name,actor.role]);
    let state:State=await getPostgresState();
    assert.deepEqual(state.shifts[0].responsibles,['Shalu']);
    const run=async(type:string,values:Record<string,unknown>,actor=salon)=>{
      state=await mutatePostgres({type,revision:state.revision,...values},actor);return state;
    };
    assert.equal(state.products.length,2);
    console.log('OK: migración local conserva el turno de tarde legado con su responsable.');
    await run('close',{counts:{'1':0,'2':0}});
    await assert.rejects(()=>run('open',{date:limaDate(),period:'Mañana',responsibles:[]}));
    await run('open',{date:limaDate(),period:'Mañana',responsibles:['Shalu','Karla']});
    const morning=state.shifts.at(-1)!;
    await run('addWaiters',{names:['Nicol']});
    const revision=state.revision;
    const joins=await Promise.allSettled(['Emilia','Mapi'].map(name=>mutatePostgres({type:'addWaiters',revision,names:[name]},salon)));
    assert.equal(joins.filter(result=>result.status==='fulfilled').length,1);
    state=await getPostgresState();
    assert.equal(state.shifts.at(-1)!.responsibles!.length,4);
    await assert.rejects(()=>run('addWaiters',{names:['Santiago']}));
    await assert.rejects(()=>run('addWaiters',{names:['Shalu']}));
    const firstProduction={type:'produceBatch',revision:state.revision,operationId:crypto.randomUUID(),date:yesterday,responsible:'Joel',items:[{productId:'1',quantity:2}]} as const;
    state=await mutatePostgres(firstProduction,cocina);
    const oldest=state.lots[0].id;
    await run('produceBatch',{operationId:crypto.randomUUID(),date:limaDate(),responsible:'Alex',items:[{productId:'1',quantity:10},{productId:'2',quantity:10}]},cocina);
    const newer=state.lots[1].id;
    const beforeRetry=structuredClone(state);
    await mutatePostgres(firstProduction,cocina);
    assert.deepEqual(await getPostgresState(),beforeRetry);
    await assert.rejects(()=>mutatePostgres({...firstProduction,items:[{productId:'1',quantity:3}]},cocina));
    const batch={type:'replenishBatch',revision:state.revision,operationId:crypto.randomUUID(),items:[{productId:'1',quantity:5},{productId:'2',quantity:4}]} as const;
    state=await mutatePostgres(batch,salon);
    assert.equal(state.lots.find(l=>l.id===oldest)!.quantity,0);
    assert.equal(state.lots.find(l=>l.id===newer)!.quantity,7);
    assert.equal(state.lots.find(l=>l.productId==='2')!.quantity,6);
    assert.equal(state.shifts.at(-1)!.rows[0].incoming,5);
    const afterBatch=structuredClone(state);
    await mutatePostgres(batch,salon);
    assert.deepEqual(await getPostgresState(),afterBatch);
    await assert.rejects(()=>run('replenishBatch',{operationId:crypto.randomUUID(),items:[{productId:'1',quantity:1},{productId:'2',quantity:99}]}));
    assert.deepEqual(await getPostgresState(),afterBatch);
    await isolated.query("ALTER TABLE movimiento_inventario ADD CONSTRAINT fallo_batch CHECK(NOT(tipo='reposicion' AND sentido='entrada' AND id_producto=2 AND cantidad=1))");
    await assert.rejects(()=>run('replenishBatch',{operationId:crypto.randomUUID(),items:[{productId:'1',quantity:1},{productId:'2',quantity:1}]}));
    assert.deepEqual(await getPostgresState(),afterBatch);
    await isolated.query('ALTER TABLE movimiento_inventario DROP CONSTRAINT fallo_batch');
    await run('correctShift',{shiftId:morning.id,productId:'1',incoming:3,reason:'Se ingresaron dos unidades de más'});
    assert.equal(state.lots.find(l=>l.id===oldest)!.quantity,0);
    assert.equal(state.lots.find(l=>l.id===newer)!.quantity,9);
    await run('correctShift',{shiftId:morning.id,productId:'1',incoming:5,reason:'Restaurar ingreso para el escenario siguiente'});
    assert.equal(state.lots.find(l=>l.id===newer)!.quantity,7);
    await assert.rejects(()=>run('correctProduction',{operationId:crypto.randomUUID(),lotId:oldest,quantity:1,responsible:'Joel',reason:'No se puede reducir lo consumido'},cocina));
    await run('correctProduction',{operationId:crypto.randomUUID(),lotId:newer,quantity:8,responsible:'Alex',reason:'Se escribieron dos de más'},cocina);
    assert.equal(state.lots.find(l=>l.id===newer)!.quantity,5);
    assert.equal(state.lots.find(l=>l.id===newer)!.producedQuantity,8);
    assert.equal(state.movements.filter(m=>m.type==='Producción'&&m.lotId===newer).reduce((sum,m)=>sum+m.quantity,0),10);
    await assert.rejects(()=>run('correctProduction',{operationId:crypto.randomUUID(),lotId:newer,quantity:9,responsible:'Alex',reason:'No autorizado'},salon));
    console.log('OK: ingresos múltiples FIFO, equipo máximo4, doble envío idempotente y corrección de producción preservan saldos.');
    const shiftId=morning.id;
    const initial=await getClosingDraft(shiftId,salon);
    assert(initial.fields.every(f=>f.value===null&&f.version===0));
    await assert.rejects(()=>saveClosingDraft({shiftId,fields:[{productId:'1',value:1,version:0}]},cocina));
    const saved=await saveClosingDraft({shiftId,fields:[{productId:'1',value:2,version:0},{productId:'2',value:0,version:0}]},salon);
    assert.equal(saved.fields.find(f=>f.productId==='1')!.version,1);
    assert.equal(saved.fields.find(f=>f.productId==='2')!.value,0);
    const duplicateSave=await saveClosingDraft({shiftId,fields:[{productId:'1',value:2,version:0}]},salon);
    assert.equal(duplicateSave.fields.find(f=>f.productId==='1')!.version,1);
    const racing=await Promise.allSettled([3,4].map(value=>saveClosingDraft({shiftId,fields:[{productId:'1',value,version:1}]},salon)));
    assert.equal(racing.filter(r=>r.status==='fulfilled').length,1);
    assert(racing.some(r=>r.status==='rejected'&&r.reason instanceof DraftConflictError));
    const resumed=await getClosingDraft(shiftId,salon);
    assert.equal(resumed.fields.find(f=>f.productId==='1')!.version,2);
    const sessionId=crypto.randomUUID();
    await isolated.query('INSERT INTO sesiones_aplicacion VALUES($1,$2,1)',[sessionId,salon.id]);
    const oldSession={...salon,sessionId,accessVersion:1};
    await getClosingDraft(shiftId,oldSession);
    await isolated.query('INSERT INTO sesiones_revocadas VALUES($1,$2)',[sessionId,salon.id]);
    await assert.rejects(()=>saveClosingDraft({shiftId,fields:[{productId:'1',value:0,version:2}]},oldSession));
    assert.deepEqual(await getClosingDraft(shiftId,salon),resumed);
    await assert.rejects(()=>run('close',{counts:{'1':0,'2':0},draftVersions:{'1':0,'2':0}}));
    const final=await saveClosingDraft({shiftId,fields:resumed.fields.map(f=>({...f,value:0}))},salon);
    await run('close',{counts:Object.fromEntries(final.fields.map(f=>[f.productId,f.value])),draftVersions:Object.fromEntries(final.fields.map(f=>[f.productId,f.version]))});
    await assert.rejects(()=>saveClosingDraft({shiftId,fields:[{productId:'1',value:1,version:3}]},salon));
    await assert.rejects(()=>run('open',{date:limaDate(),period:'Tarde',responsibles:['Shalu']}));
    await run('open',{date:limaDate(),period:'Tarde',responsibles:['Shalu','Karla']});
    const replacementShift=state.shifts.at(-1)!.id;
    const pendingBefore=await saveClosingDraft({shiftId:replacementShift,fields:[{productId:'1',value:0,version:0}]},salon);
    const beforeReplace=structuredClone(state);
    const primaryChange={type:'replaceWaiter',revision:state.revision,shiftId:replacementShift,outgoing:'Shalu',replacement:'Santiago',reason:'No asistió',operationId:crypto.randomUUID()};
    state=await mutatePostgres(primaryChange,salon);
    assert.deepEqual(state.shifts.at(-1)!.responsibles,['Santiago','Karla']);assert.equal(state.shifts.at(-1)!.responsible,'Santiago');
    assert.deepEqual(state.shifts.at(-1)!.rows,beforeReplace.shifts.at(-1)!.rows);assert.deepEqual(state.movements,beforeReplace.movements);assert.deepEqual(state.lots,beforeReplace.lots);assert.deepEqual(state.supplies,beforeReplace.supplies);
    assert.deepEqual(await getClosingDraft(replacementShift,salon),pendingBefore);
    const persistedReplace=structuredClone(state);state=await mutatePostgres(primaryChange,salon);assert.deepEqual(state,persistedReplace);
    await assert.rejects(()=>mutatePostgres({...primaryChange,reason:'Otro motivo'},salon));
    await assert.rejects(()=>run('replaceWaiter',{shiftId:morning.id,outgoing:'Shalu',replacement:'Nicol',reason:'Cerrado',operationId:crypto.randomUUID()}));
    await assert.rejects(()=>run('replaceWaiter',{shiftId:replacementShift,outgoing:'Karla',replacement:'Santiago',reason:'Duplicado',operationId:crypto.randomUUID()}));
    await assert.rejects(()=>run('replaceWaiter',{shiftId:replacementShift,outgoing:'Karla',replacement:'Nicol',reason:'Sin permiso',operationId:crypto.randomUUID()},cocina));
    const stored=(await isolated.query('SELECT u.nombre_usuario FROM turnos t JOIN usuarios u ON u.id_usuario=t.id_responsable WHERE t.id_turno=$1',[replacementShift])).rows[0];assert.equal(stored.nombre_usuario,'Santiago');
    const audit=(await isolated.query("SELECT detalle FROM auditoria_acceso WHERE accion='inventory.replaceWaiter'")).rows;assert.equal(audit.length,1);assert.equal(audit[0].detalle.outgoing,'Shalu');assert.equal(audit[0].detalle.replacement,'Santiago');assert(audit[0].detalle.history.note.includes('No asistió'));
    const racingReplace=await Promise.allSettled(['Nicol','Mapi'].map(name=>mutatePostgres({type:'replaceWaiter',revision:state.revision,shiftId:replacementShift,outgoing:'Karla',replacement:name,reason:'Relevo',operationId:crypto.randomUUID()},salon)));assert.equal(racingReplace.filter(r=>r.status==='fulfilled').length,1);state=await getPostgresState();
    const keptTeam=structuredClone(state.shifts.at(-1)!.responsibles);
    await isolated.query(`CREATE FUNCTION reject_team_change() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN RAISE EXCEPTION ''Fallo simulado''; END'; CREATE TRIGGER fail_replace BEFORE UPDATE OF id_responsable ON turnos FOR EACH ROW EXECUTE FUNCTION reject_team_change()`);
    await assert.rejects(()=>run('replaceWaiter',{shiftId:replacementShift,outgoing:'Santiago',replacement:'Diogo',reason:'Rollback',operationId:crypto.randomUUID()}));assert.deepEqual(await getPostgresState(),state);assert.deepEqual((await getPostgresState()).shifts.at(-1)!.responsibles,keptTeam);
    await isolated.query('DROP TRIGGER fail_replace ON turnos');
    console.log('OK: reemplazo principal, conservación de conteos/historial, doble envío, concurrencia, permisos, auditoría y rollback del cambio de equipo.');
    const afternoon=await getClosingDraft(state.shifts.at(-1)!.id,salon);
    assert(afternoon.fields.every(f=>f.productId==='1'?f.value===0:f.value===null));
    console.log('OK: borradores persisten tras cambio de sesión, CAS impide sobrescrituras, Cocina no escribe, cierre rechaza versiones antiguas y tarde exige2 mozos.');
    await run('supplyMove',{supplyId:'liquido-0',action:'conteo',quantity:600,responsible:'Joel'},cocina);
    await run('supplyMove',{supplyId:'liquido-0',action:'salida',quantity:10,responsible:'Shalu'},salon);
    const visibleSalon=await inventoryForActor(state,salon),visibleKitchen=await inventoryForActor(state,cocina);
    assert.equal(visibleSalon.lots.length,0);assert(visibleSalon.replenishment!.some(p=>p.maximum>0));
    assert.equal(visibleKitchen.shifts.length,0);assert(visibleKitchen.transferShifts!.some(s=>s.rows.some(r=>r.incoming>0)));
    assert.equal(visibleSalon.supplyMovements!.length,1);assert.equal(visibleSalon.supplyMovements![0].responsible,'Shalu');
    assert.equal(visibleKitchen.supplyMovements!.length,1);assert.equal(visibleKitchen.supplyMovements![0].responsible,'Joel');
    const kitchenHistory=await readOperationHistory(new URLSearchParams(),cocina,state);
    assert(kitchenHistory.entries.some(e=>e.action==='produceBatch'));assert(kitchenHistory.entries.every(e=>e.area==='cocina'));assert(!kitchenHistory.entries.some(e=>e.action==='close'));
    const salonHistory=await readOperationHistory(new URLSearchParams(),salon,state);
    assert(salonHistory.entries.some(e=>e.action==='close'));assert(salonHistory.entries.every(e=>e.area==='mozo'));assert(!salonHistory.entries.some(e=>e.action==='produceBatch'));
    await isolated.query('INSERT INTO auditoria_acceso(auth_id,accion,detalle) VALUES(NULL,$1,$2)',['inventory.produce',JSON.stringify({responsable:'Shalu',productId:'1'})]);
    assert(!(await readOperationHistory(new URLSearchParams(),salon,state)).entries.some(e=>e.account==='Cuenta anterior'));
    assert((await readOperationHistory(new URLSearchParams(),admin,state)).entries.some(e=>e.account==='Cuenta anterior'));
    await assert.rejects(()=>readOperationHistory(new URLSearchParams({account:cocina.id}),salon,state));
    await isolated.query('INSERT INTO auditoria_acceso(auth_id,accion,detalle) SELECT $1,$2,$3 FROM generate_series(1,55)',[salon.id,'inventory.open',JSON.stringify({responsable:'Shalu'})]);
    const firstPage=await readOperationHistory(new URLSearchParams(),salon,state);assert.equal(firstPage.entries.length,50);assert(firstPage.nextCursor);
    const secondPage=await readOperationHistory(new URLSearchParams({cursor:firstPage.nextCursor!}),salon,state);
    assert(secondPage.entries.every(e=>!firstPage.entries.some(f=>f.id===e.id)));
    assert.deepEqual(await getPostgresState(),state);
    const closeTeam=state.shifts.at(-1)!.responsibles;
    const pendingClose=await getClosingDraft(replacementShift,salon);
    const readyClose=await saveClosingDraft({shiftId:replacementShift,fields:pendingClose.fields.map(field=>({...field,value:0}))},salon);
    await run('close',{counts:Object.fromEntries(readyClose.fields.map(field=>[field.productId,field.value])),draftVersions:Object.fromEntries(readyClose.fields.map(field=>[field.productId,field.version]))});
    assert.deepEqual(state.shifts.at(-1)!.responsibles,closeTeam);assert.equal(state.shifts.at(-1)!.status,'closed');
    const closingAudit=(await isolated.query("SELECT detalle FROM auditoria_acceso WHERE accion='inventory.close' ORDER BY id DESC LIMIT 1")).rows[0];assert.deepEqual(closingAudit.detalle.history.responsibles,closeTeam);
    console.log('OK: el cierre persistido y su auditoría usan el equipo actualizado después del reemplazo.');
    console.log('OK: respuestas por cuenta sin ventas de Cocina ni lotes de Salón; historial y movimientos de insumos filtrados por cuenta autenticada, datos antiguos solo para Administración, filtros protegidos y paginación sin duplicados.');

  }finally{
    globals.lunePgPool=pool;await isolated?.end();
    try{if(created)await pool.query(`DROP SCHEMA "${schema}" CASCADE`);}finally{await pool.end();}
  }
}
main().catch(error=>{console.error('Falló la prueba beta aislada; Supabase no se utiliza.');console.error(databaseError(error).message);process.exitCode=1;});
